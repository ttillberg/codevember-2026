/**
 * Convert an ASCII/PETSCII character code (0..255) to a C64 screen code (0..127),
 * or -1 if it is a non-printing control code.
 */
export function petsciiToScreenCode(code: number): number {
  const c = code & 0xff;
  // Standard ASCII lowercase -> uppercase PETSCII (authentic C64 default mode)
  if (c >= 0x61 && c <= 0x7a) return c - 0x60; // 'a'..'z' -> 0x01..0x1A
  if (c >= 0x40 && c <= 0x5f) return c - 0x40; // '@', 'A'..'Z', '[', '\', ']', '^', '_'
  if (c >= 0x20 && c <= 0x3f) return c;        // space .. '?'
  if (c >= 0xa0 && c <= 0xbf) return c - 0x40; // graphics 0x60..0x7F
  if (c >= 0xc0 && c <= 0xdf) return c - 0x80; // graphics 0x40..0x5F (includes 205=0x4D, 206=0x4E!)
  if (c >= 0xe0 && c <= 0xfe) return c - 0x80; // mirror graphics
  if (c === 0xff) return 0x5e;                 // pi
  return -1;
}

/**
 * Convert a C64 screen code (0..127) back into an uppercase ASCII string character
 * for reading edited lines from screen memory.
 */
export function screenCodeToAscii(sc: number): string {
  const c = sc & 0x7f;
  if (c === 0x00) return '@';
  if (c >= 0x01 && c <= 0x1a) return String.fromCharCode(c + 0x40); // A..Z
  if (c === 0x1b) return '[';
  if (c === 0x1c) return '£';
  if (c === 0x1d) return ']';
  if (c === 0x1e) return '^';
  if (c === 0x1f) return '_';
  if (c >= 0x20 && c <= 0x3f) return String.fromCharCode(c);
  // Graphic characters preserved as high codes so PRINT CHR$ or editing keeps them
  if (c >= 0x40 && c <= 0x5f) return String.fromCharCode(c + 0x80);
  if (c >= 0x60 && c <= 0x7f) return String.fromCharCode(c + 0x40);
  return ' ';
}

