// 8x8 bitmap glyphs indexed by C64 screen code (0..127).
// Screen codes 128..255 are reverse video of 0..127 (handled by renderer).
// Based on the classic Commodore 64 901225-01 uppercase/graphics character ROM.
export const CHAR_ROM = new Uint8Array(128 * 8);

function setGlyph(screenCode: number, rows: number[]) {
  const base = (screenCode & 0x7f) * 8;
  for (let i = 0; i < 8; i++) CHAR_ROM[base + i] = rows[i] ?? 0;
}

